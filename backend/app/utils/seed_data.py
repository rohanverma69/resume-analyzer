def seed_jobs_if_empty(db, job_model):
    """Seed sample jobs if none exist in the database."""
    count = job_model.query.count()
    if count == 0:
        for job_data in SAMPLE_JOBS:
            job = job_model(
                title=job_data["title"],
                company=job_data["company"],
                location=job_data["location"],
                job_type=job_data["job_type"],
                experience_level=job_data["experience_level"],
                min_experience_years=job_data["min_experience_years"],
                salary_range=job_data["salary_range"],
                description=job_data["description"],
                required_skills=job_data["required_skills"],
                preferred_skills=job_data.get("preferred_skills", []),
                is_sample=job_data.get("is_sample", True),
            )
            db.session.add(job)
        db.session.commit()
        return len(SAMPLE_JOBS)
    return 0


def seed_demo_user_if_empty(db, user_model):
    """Ensure standard demo accounts exist for easy testing and evaluation."""
    demo_accounts = [
        ("demo.candidate@careerai.local", "Demo Candidate", "DemoCareer2026!"),
        ("demo@careerai.com", "Demo User", "DemoCareer2026!"),
    ]
    created = 0
    for email, name, password in demo_accounts:
        user = user_model.query.filter_by(email=email).first()
        if not user:
            u = user_model(email=email, full_name=name)
            u.set_password(password)
            db.session.add(u)
            created += 1
    if created > 0:
        db.session.commit()
    return created

